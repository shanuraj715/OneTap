import { chromium } from "playwright";
// Colours, stats + sharing chats out, clean up (with the date picker), and message delete (confirm, Enter / Esc, for everyone).
const AD = "http://localhost:3171";
const browser = await chromium.launch();
let pass = 0, fail = 0;
const ok = (c, l, x = "") => { c ? pass++ : fail++; console.log(`${c ? "PASS" : "FAIL"}  ${l}${x ? "  — " + x : ""}`); };
const problems = [];
const ctx = await browser.newContext({ viewport: { width: 1360, height: 900 } });
const page = await ctx.newPage();
page.on("console", (m) => { if (["error", "warning"].includes(m.type()) && !/Failed to load resource|example\.com/.test(m.text())) problems.push(m.text().slice(0, 200)); });
page.on("pageerror", (e) => problems.push(`pageerror: ${String(e).slice(0, 200)}`));
await page.goto(AD + "/", { waitUntil: "load" });
await page.fill('input[type="email"]', "o@acme.test"); await page.fill('input[type="password"]', "Owner123!");
await page.getByRole("button", { name: /sign in|log in/i }).first().click();
await page.waitForSelector("text=Orders");

console.log("=== colours");
await page.goto(AD + "/whatsapp/chats", { waitUntil: "load" });
await page.waitForSelector("text=Riya Sharma");
await page.waitForTimeout(800);
const chip = page.locator("aside button", { hasText: "Riya Sharma" }).locator("span", { hasText: /^via / }).first();
const bg = await chip.evaluate((el) => getComputedStyle(el).backgroundColor);
ok(bg !== "rgba(0, 0, 0, 0)" && bg !== "rgb(255, 255, 255)", "the chip is filled with its number's colour", bg);
await page.goto(AD + "/whatsapp/numbers", { waitUntil: "load" });
await page.waitForSelector("text=Chats by number");
await page.getByRole("button", { name: "Edit Counter phone" }).click();
await page.getByRole("radio", { name: "#6A1B9A" }).click();
ok(/via Counter phone/.test(await page.getByRole("dialog").innerText()), "the colour picker previews the chip");
await page.getByRole("button", { name: "Save" }).click();
await page.waitForTimeout(800);
await page.goto(AD + "/whatsapp/chats", { waitUntil: "load" });
await page.waitForSelector("text=Riya Sharma");
await page.waitForTimeout(800);
const bg2 = await page.locator("aside button", { hasText: "Riya Sharma" }).locator("span", { hasText: /^via / }).first().evaluate((el) => getComputedStyle(el).backgroundColor);
ok(bg2 === "rgb(106, 27, 154)", "a new colour shows on every chat of that number", bg2);
const fg = await page.locator("aside button", { hasText: "Riya Sharma" }).locator("span", { hasText: /^via / }).first().evaluate((el) => getComputedStyle(el).color);
ok(fg === "rgb(255, 255, 255)", "…with readable (white) text on the dark purple", fg);
await page.getByRole("button", { name: /Riya Sharma/ }).click();
await page.waitForSelector("text=2 plates of kurkure");
const headChip = await page.getByRole("button", { name: /Sent from Counter phone/ }).evaluate((el) => getComputedStyle(el).backgroundColor);
ok(headChip === "rgb(106, 27, 154)", "the chat header's number chip wears the colour too", headChip);
await page.screenshot({ path: "wa2-1-colours.png" });

console.log("=== delete a message");
const menuMsg = page.locator(".wa-msg", { hasText: "Here's today's menu" });
await menuMsg.hover();
await menuMsg.getByRole("button", { name: "Delete this message" }).click();
let dlg = page.getByRole("dialog", { name: "Delete this message?" });
await dlg.waitFor();
ok(await dlg.getByRole("button", { name: "Delete for everyone" }).isVisible() && await dlg.getByRole("button", { name: "Delete for me" }).isVisible(), "a recent message of ours offers 'Delete for everyone' and 'Delete for me'");
ok(/Enter: Delete for everyone · Esc: cancel/.test(await dlg.innerText()), "the box says what Enter and Esc do");
await page.screenshot({ path: "wa2-2-delete.png" });
await page.keyboard.press("Escape");
await page.waitForTimeout(300);
ok((await page.getByRole("dialog", { name: "Delete this message?" }).count()) === 0 && (await menuMsg.count()) === 1, "Esc closes it and nothing is deleted");
await menuMsg.hover();
await menuMsg.getByRole("button", { name: "Delete this message" }).click();
await page.getByRole("dialog", { name: "Delete this message?" }).waitFor();
await page.keyboard.press("Enter");
await page.waitForSelector("text=Deleting for everyone…", { timeout: 10000 }).then(() => ok(true, "Enter deletes it for everyone (handed to WhatsApp)")).catch(() => ok(false, "Enter deletes it for everyone (handed to WhatsApp)"));
const inMsg = page.locator(".wa-msg", { hasText: "Can you send the menu?" });
await inMsg.hover();
await inMsg.getByRole("button", { name: "Delete this message" }).click();
dlg = page.getByRole("dialog", { name: "Delete this message?" });
await dlg.waitFor();
ok(!(await dlg.getByRole("button", { name: "Delete for everyone" }).isVisible().catch(() => false)) && /Only the customer can delete their own message/.test(await dlg.innerText()), "a customer's message can only be deleted here, and the box says why");
await dlg.getByRole("button", { name: "Cancel" }).focus();
await page.keyboard.press("Enter");
await page.waitForTimeout(400);
ok((await inMsg.count()) === 1 && (await page.getByRole("dialog").count()) === 0, "Enter on 'Cancel' cancels (it doesn't delete)");
await inMsg.hover();
await inMsg.getByRole("button", { name: "Delete this message" }).click();
await page.getByRole("dialog", { name: "Delete this message?" }).getByRole("button", { name: "Delete for me" }).click();
await page.waitForTimeout(900);
ok((await inMsg.count()) === 0, "'Delete for me' removes it");

console.log("=== stats and sharing out");
await page.goto(AD + "/whatsapp/numbers", { waitUntil: "load" });
await page.waitForSelector("text=Chats by number");
await page.waitForTimeout(800);
const statsText = await page.locator("table").innerText();
ok(/Counter phone\s+3/.test(statsText.replace(/\n/g, " ")) && /Number 2 · offline\s+1/.test(statsText.replace(/\n/g, " ")), "stats: chats per number", statsText.split("\n").slice(1, 4).join(" | "));
await page.screenshot({ path: "wa2-3-stats.png", fullPage: true });
await page.getByRole("button", { name: "Share chats out" }).click();
dlg = page.getByRole("dialog", { name: "Share chats out between numbers" });
await dlg.waitFor();
await page.waitForTimeout(1200);
let t = await dlg.innerText();
ok(/Move \d+ chats?/.test(t), "the box previews how many chats move", t.match(/Move \d+ chats?/)?.[0]);
await page.screenshot({ path: "wa2-4-share.png" });
await dlg.getByLabel("What Counter phone does").selectOption("give");
await dlg.getByLabel("What Number 2 does").selectOption("give");
await page.waitForTimeout(1200);
t = await dlg.innerText();
ok(/Move 4 chats/.test(t), "giving away numbers 1 and 2 moves all 4 of their chats into Number 3", t.match(/Move \d+ chats/)?.[0]);
await page.keyboard.press("Escape");
await page.getByRole("button", { name: "Share chats out" }).click();
dlg = page.getByRole("dialog", { name: "Share chats out between numbers" });
await dlg.waitFor();
await page.waitForTimeout(1200);
const label = (await dlg.innerText()).match(/Move (\d+) chats?/);
await dlg.getByRole("button", { name: /^Move \d+ chats?$/ }).click();
await page.waitForSelector("text=/chats? moved/", { timeout: 10000 });
ok(true, `sharing out moves them (${label?.[1]})`);
await page.getByRole("button", { name: "Done" }).click();
await page.waitForTimeout(1500);
const after = (await page.locator("table").innerText()).replace(/\n/g, " ");
ok(/Number 3\s+[1-9]/.test(after), "…and Number 3 now has chats", after.slice(0, 160));

console.log("=== clean up");
await page.getByRole("link", { name: "Clean up", exact: true }).click();
await page.waitForSelector("text=Clean up old history");
await page.getByLabel("Number of days").fill("30");
await page.waitForTimeout(1200);
ok(/2 messages from before .* in 1 chat/.test(await page.locator("body").innerText()), "older than 30 days: 2 messages in 1 chat", (await page.locator("body").innerText()).match(/\d+ messages? from before[^.]*\./)?.[0]);
await page.locator('input[name="wa-when"]').nth(1).check();
await page.locator("text=Pick a date").or(page.locator('[style*="cursor: pointer"]', { hasText: /\d{4}/ })).first().click().catch(() => {});
await page.waitForTimeout(500);
await page.screenshot({ path: "wa2-5-cleanup-date.png", fullPage: true });
await page.keyboard.press("Escape").catch(() => {});
await page.locator('input[name="wa-when"]').first().check();
await page.getByRole("button", { name: "Remove…" }).click();
dlg = page.getByRole("dialog", { name: "Remove 2 messages?" });
await dlg.waitFor();
await page.keyboard.press("Enter");
await page.waitForSelector("text=Removed 2 messages.", { timeout: 10000 }).then(() => ok(true, "Enter in the confirm box removes them")).catch(() => ok(false, "Enter in the confirm box removes them"));
await page.waitForTimeout(1200);
ok(/0 messages from before/.test(await page.locator("body").innerText()), "…and nothing that old is left");

console.log(`\nTOTAL ${pass} passed, ${fail} failed`);
console.log("console problems:", problems.length ? problems : "none");
await browser.close();
