import { chromium } from "playwright";
const browser = await chromium.launch();
let pass = 0, fail = 0;
const ok = (c, l, x = "") => { c ? pass++ : fail++; console.log(`${c ? "PASS" : "FAIL"}  ${l}${x ? "  — " + x : ""}`); };
const errs = [];
const page = await browser.newPage({ viewport: { width: 1360, height: 900 } });
page.on("pageerror", (e) => errs.push(String(e).slice(0, 200)));
await page.goto("http://localhost:3171/", { waitUntil: "load" });
await page.fill('input[type="email"]', "o@acme.test"); await page.fill('input[type="password"]', "Owner123!");
await page.getByRole("button", { name: /sign in|log in/i }).first().click();
await page.waitForSelector("text=Orders");
await page.goto("http://localhost:3171/whatsapp/chats", { waitUntil: "load" });
await page.waitForSelector("text=Riya Sharma");
const names = async () => { await page.waitForTimeout(900); return await page.locator("aside > div").last().locator(":scope > button strong").allInnerTexts(); };
const chipOf = (name) => page.locator("aside button", { hasText: name }).locator("span", { hasText: /^via / }).first();
ok(await chipOf("Riya Sharma").isVisible(), "each chat shows 'via <number>' as a chip", await chipOf("Riya Sharma").innerText());
ok(/offline/.test(await chipOf("Kabir").innerText()), "…saying when that number is offline", await chipOf("Kabir").innerText());
const bg = await chipOf("Riya Sharma").evaluate((el) => getComputedStyle(el).borderRadius);
ok(parseFloat(bg) > 50, "…drawn as a rounded chip");
ok((await names()).length === 4, "All: every chat", (await names()).join(", "));
await page.getByRole("button", { name: "Unread", exact: true }).click();
ok(JSON.stringify(await names()) === '["Riya Sharma"]', "Unread", (await names()).join(", "));
await page.getByRole("button", { name: "Needs reply" }).click();
ok(JSON.stringify(await names()) === '["Riya Sharma"]', "Needs reply: the customer wrote last", (await names()).join(", "));
await page.getByRole("button", { name: "New", exact: true }).click();
let n = await names();
ok(n.length === 2 && n.includes("Meera") && n.includes("+91 98444 44444"), "New: never wrote to us", n.join(", "));
await page.getByRole("button", { name: "No offers" }).click();
ok(JSON.stringify(await names()) === '["Kabir"]', "No offers: said STOP", (await names()).join(", "));
await page.getByRole("button", { name: "All", exact: true }).click();
await page.getByLabel("Filter by number").selectOption({ label: "Number 2 (offline)" });
ok(JSON.stringify(await names()) === '["Kabir"]', "filter by number", (await names()).join(", "));
await page.getByLabel("Filter by number").selectOption({ label: "Counter phone" });
await page.getByRole("button", { name: "No offers" }).click();
await page.waitForTimeout(900);
ok(await page.getByText("No chats match.").isVisible(), "filters combine, and an empty result says so");
await page.getByRole("button", { name: "Clear filters" }).click();
ok((await names()).length === 4 && (await page.getByLabel("Filter by number").inputValue()) === "", "'Clear filters' resets everything");
await page.screenshot({ path: "wa-filters.png", clip: { x: 250, y: 160, width: 360, height: 560 } });
const p2 = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2 });
p2.on("pageerror", (e) => errs.push(String(e).slice(0, 200)));
await p2.context().addCookies(await page.context().cookies());
await p2.goto("http://localhost:3171/whatsapp/chats", { waitUntil: "load" });
await p2.waitForSelector("text=Riya Sharma");
ok((await p2.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)) <= 1, "phone: the filter row scrolls inside itself, the page doesn't");
await p2.screenshot({ path: "wa-filters-phone.png" });
console.log(`TOTAL ${pass} passed, ${fail} failed`, "| page errors:", errs.length ? errs : "none");
await browser.close();
